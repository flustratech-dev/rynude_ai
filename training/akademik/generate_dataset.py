            "Konsistensi penilaian diukur menggunakan Consistency Ratio (CR) dengan formula:\n"
            "CR = CI / RI\n"
            "di mana CI (Consistency Index) = (lambda_max - n) / (n - 1),\n"
            "RI (Random Consistency Index) adalah nilai rata-rata CI untuk matriks acak berukuran n,\n"
            "dan lambda_max adalah eigenvalue terbesar dari matriks perbandingan.\n\n"
            "Saaty (1980) menetapkan bahwa penilaian dianggap konsisten jika CR ≤ 0,10 (10%). "
            "Jika CR > 0,10, maka penilaian perlu direvisi karena tingkat inkonsistensi yang "
            "terlalu tinggi dapat menghasilkan bobot yang tidak valid.\n\n"
            "2.3 Metode TOPSIS\n\n"
            "2.3.1 Konsep Dasar TOPSIS\n\n"
            "Technique for Order of Preference by Similarity to Ideal Solution (TOPSIS) adalah "
            "metode pengambilan keputusan multikriteria yang dikembangkan oleh Hwang dan Yoon "
            "(1981) berdasarkan konsep bahwa alternatif terpilih harus memiliki jarak geometris "
            "terpendek dari solusi ideal positif dan jarak geometris terpanjang dari solusi "
            "ideal negatif.\n\n"
            "2.3.2 Langkah-langkah Algoritma TOPSIS\n\n"
            "Langkah 1: Pembentukan matriks keputusan X berukuran m x n, di mana m adalah "
            "jumlah alternatif (supplier) dan n adalah jumlah kriteria.\n\n"
            "Langkah 2: Normalisasi matriks keputusan menggunakan normalisasi Euclidean:\n"
            "r_ij = x_ij / sqrt(sum(x_ij^2)) untuk i=1..m\n\n"
            "Langkah 3: Pembentukan matriks keputusan berbobot:\n"
            "v_ij = w_j * r_ij\n"
            "di mana w_j adalah bobot kriteria ke-j yang diperoleh dari metode AHP.\n\n"
            "Langkah 4: Penentuan solusi ideal positif (A+) dan solusi ideal negatif (A-):\n"
            "A+ = {max(v_ij) jika j benefit, min(v_ij) jika j cost}\n"
            "A- = {min(v_ij) jika j benefit, max(v_ij) jika j cost}\n\n"
            "Langkah 5: Perhitungan jarak setiap alternatif dari solusi ideal:\n"
            "D_i+ = sqrt(sum((v_ij - v_j+)^2))\n"
            "D_i- = sqrt(sum((v_ij - v_j-)^2))\n\n"
            "Langkah 6: Perhitungan nilai preferensi relatif:\n"
            "C_i = D_i- / (D_i+ + D_i-)\n\n"
            "Langkah 7: Peringkat alternatif berdasarkan nilai C_i tertinggi.\n\n"
